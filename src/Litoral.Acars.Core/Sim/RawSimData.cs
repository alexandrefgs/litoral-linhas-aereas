namespace Litoral.Acars.Core.Sim;

public sealed record RawSimData(
    long Latitude,
    long Longitude,
    long Altitude,
    int RadioAltitude,
    int Ias,
    int GroundSpeed,
    uint Heading,
    int VerticalSpeed,
    int Pitch,
    int FlapsHandle,
    short FlapDetents,
    int GearHandle,
    short OnGround,
    short ParkingBrake,
    IReadOnlyList<short> EngineCombustion,
    int FuelPounds,
    int TouchdownVerticalSpeed,
    byte Overspeed,
    byte Stall,
    short Slew,
    short Paused,
    short SimRate,
    short Crashed)
{
    public SimSnapshot ToSnapshot(DateTime at) => new(
        at,
        FsuipcConvert.Latitude(Latitude),
        FsuipcConvert.Longitude(Longitude),
        FsuipcConvert.AltitudeFt(Altitude),
        FsuipcConvert.RadioAltitudeFt(RadioAltitude),
        FsuipcConvert.AirspeedKt(Ias),
        FsuipcConvert.GroundSpeedKt(GroundSpeed),
        FsuipcConvert.HeadingDeg(Heading),
        FsuipcConvert.VerticalSpeedFpm(VerticalSpeed),
        FsuipcConvert.PitchDeg(Pitch),
        FlapsHandle,
        FlapDetents,
        FsuipcConvert.GearDown(GearHandle),
        FsuipcConvert.IsSet(OnGround),
        FsuipcConvert.IsSet(ParkingBrake),
        EngineCombustion.Select(e => FsuipcConvert.IsSet(e)).ToList(),
        Math.Round(FsuipcConvert.PoundsToKg(FuelPounds), 1),
        FsuipcConvert.VerticalSpeedFpm(TouchdownVerticalSpeed),
        FsuipcConvert.IsSet(Overspeed),
        FsuipcConvert.IsSet(Stall),
        FsuipcConvert.IsSet(Slew),
        FsuipcConvert.IsSet(Paused),
        SimRate > 0 ? FsuipcConvert.SimRate(SimRate) : 1,
        FsuipcConvert.IsSet(Crashed));
}